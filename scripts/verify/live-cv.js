function validateMissingAdaptationPlanFailure() {
  const missingPlanRoot = path.join(validationRoot, "missing-adaptation-plan");
  const evaluation = setupSourceWorkspace(missingPlanRoot);
  const withoutPlan = { ...evaluation };
  delete withoutPlan.cv_adaptation_plan;
  writeYaml(path.join(missingPlanRoot, "students", studentId, "evaluations", `${evaluation.id}.yml`), withoutPlan);
  const missingPlanDryRun = path.join(validationRoot, "missing-plan-dry-run");
  let failed = false;
  try {
    runLiveCv({
      program: evaluation.id,
      workspace: missingPlanRoot,
      student: studentId,
      dryRunRoot: missingPlanDryRun,
    });
  } catch (error) {
    failed = /CV adaptation plan preflight failed/.test(error.message) && error.message.includes("$admissions-ops cv");
  }
  assert(failed, "Missing adaptation plan should fail before live rendering");
  assert(!fs.existsSync(path.join(missingPlanDryRun, "output", evaluation.id)), "Missing-plan failure generated output");
}

function copyFile(relativeSource, target) {
  const source = path.join(repoRoot, relativeSource);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(source, target);
}

function readYaml(file) {
  return yaml.load(fs.readFileSync(file, "utf8"));
}

function writeYaml(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, yaml.dump(value, { lineWidth: 100 }));
}

function writeText(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, value);
}

function hashFiles(root, files) {
  return Object.fromEntries(files.map((file) => [file, hashFile(path.join(root, file))]));
}

function assertHashes(root, files, expected, message) {
  for (const file of files) {
    assert(hashFile(path.join(root, file)) === expected[file], `${message}: ${file}`);
  }
}

function hashFile(file) {
  return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

function resolveMarkdownLink(baseFile, markdownLink, rootDir) {
  const match = markdownLink.match(/\]\(([^)]+)\)/);
  if (!match) return false;
  const resolved = path.resolve(path.dirname(baseFile), match[1]);
  return resolved.startsWith(rootDir) && fs.existsSync(resolved);
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

main();
