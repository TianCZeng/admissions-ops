const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");
const { REVIEW_STATUS, estimateHtmlPages } = require("../lib/cv-writer");
const { runLiveCv } = require("../cli/cv");
const {
  parseTracker,
  renderReport,
  renderTracker,
  reportFileName,
  trackerRowFromEvaluation,
} = require("../lib/program-writer");

const repoRoot = path.resolve(__dirname, "..", "..");
const validationRoot = path.join(repoRoot, "validation-output", "verify", "live-cv");
const sourceRoot = path.join(validationRoot, "source");
const studentId = "live-cv-fixture";
const studentRoot = path.join(sourceRoot, "students", studentId);
const dryRunRoot = path.join(validationRoot, "dry-run", "northbridge-msc-ai-fall-2027");

function main() {
  resetValidationRoot();
  const evaluation = setupSourceWorkspace(sourceRoot);
  const programId = evaluation.id;
  const sourceFiles = [
    `students/${studentId}/profile.yml`,
    `students/${studentId}/evidence.yml`,
    `students/${studentId}/master-cv.md`,
    `students/${studentId}/evaluations/northbridge-msc-ai-fall-2027.yml`,
    `students/${studentId}/tracker.md`,
    `students/${studentId}/reports/001-northbridge-university-2026-06-18.md`,
  ];
  const beforeDryRun = hashFiles(sourceRoot, sourceFiles);

  const dryRun = runLiveCv({
    program: programId,
    workspace: sourceRoot,
    student: studentId,
    dryRunRoot,
    write: false,
  });
  assertHashes(sourceRoot, sourceFiles, beforeDryRun, "Dry-run mutated source workspace");
  validateLiveResult(dryRun, "dry-run");
  assert(!fs.existsSync(path.join(studentRoot, "output", programId)), "Dry-run wrote into source output");

  const beforeWriteMasterCv = hashFile(path.join(studentRoot, "master-cv.md"));
  const writeResult = runLiveCv({
    program: programId,
    workspace: sourceRoot,
    student: studentId,
    write: true,
  });
  validateLiveResult(writeResult, "write");
  assert(
    hashFile(path.join(studentRoot, "master-cv.md")) === beforeWriteMasterCv,
    "Approved write mutated students/live-cv-fixture/master-cv.md"
  );
  validateReportAndTracker(studentRoot, writeResult, evaluation);
  validateTrackerNextActionSync(writeResult, evaluation);
  validateMissingStudentFailure();
  validateUnsupportedDocumentTypeFailure();
  validateMissingAdaptationPlanFailure();
  validateDocumentTypeFlagFlip();
  validateInstructionOverrideRecord();

  console.log(`Live CV runner verifies in ${path.relative(process.cwd(), validationRoot)}`);
}

function validateTrackerNextActionSync(result, evaluation) {
  const parsed = parseTracker(fs.readFileSync(result.trackerPath, "utf8"));
  assert(
    parsed.rows.length === 1 && parsed.rows[0]["Next Action"] === evaluation.next_action,
    "Write must render the tracker Next Action cell from evaluation.next_action"
  );
}

// The CLI --document-type flag wins over the plan, deletes the other type's
// artifact, persists the chosen type into the evaluation plan on --write, and
// a subsequent flag-less write reproduces every generated byte.
function validateDocumentTypeFlagFlip() {
  const flipRoot = path.join(validationRoot, "document-type-flip");
  const evaluation = setupSourceWorkspace(flipRoot);
  const evalPath = path.join(flipRoot, "students", studentId, "evaluations", `${evaluation.id}.yml`);
  // Resume-legal priorities so the flag flip passes the resume category rule;
  // the plan still records academic_cv as the agent's choice.
  const flipEvaluation = {
    ...evaluation,
    cv_adaptation_plan: {
      ...evaluation.cv_adaptation_plan,
      evidence_priorities: [
        "edu-pmc-bsc-cs",
        "research-human-feedback-thesis",
        "project-rubric-eval-dashboard",
        "course-machine-learning",
        "course-hci",
        "award-research-poster",
      ],
    },
  };
  writeYaml(evalPath, flipEvaluation);
  const flipStudentRoot = path.join(flipRoot, "students", studentId);

  const first = runLiveCv({ program: evaluation.id, workspace: flipRoot, student: studentId, write: true });
  assert(first.documentType === "academic_cv", "Flag-flip baseline should render the plan's academic CV");
  const outputDir = path.join(flipStudentRoot, "output", evaluation.id);
  assert(fs.existsSync(path.join(outputDir, "academic-cv.html")), "Flag-flip baseline missing academic-cv.html");

  const flipped = runLiveCv({
    program: evaluation.id,
    workspace: flipRoot,
    student: studentId,
    write: true,
    documentType: "admissions_resume",
  });
  assert(flipped.documentType === "admissions_resume", "--document-type should win over the plan document type");
  assert(fs.existsSync(path.join(outputDir, "admissions-resume.html")), "Flag flip missing admissions-resume.html");
  assert(!fs.existsSync(path.join(outputDir, "academic-cv.html")), "Flag flip must delete the other type's artifact");

  const evalText = fs.readFileSync(evalPath, "utf8");
  assert(/^  document_type: admissions_resume$/m.test(evalText), "--write must persist the CLI document type into cv_adaptation_plan");
  assert(!evalText.includes("document_type_rationale"), "No rationale should be persisted when no instruction-derived override is in effect");

  const trackedFiles = [
    `output/${evaluation.id}/admissions-resume.html`,
    `output/${evaluation.id}/adaptation-plan.md`,
    `output/${evaluation.id}/change-log.md`,
    `output/${evaluation.id}/evidence-map.yml`,
    "tracker.md",
    `evaluations/${evaluation.id}.yml`,
  ];
  const afterFlip = hashFiles(flipStudentRoot, trackedFiles);
  const rerun = runLiveCv({ program: evaluation.id, workspace: flipRoot, student: studentId, write: true });
  assert(rerun.documentType === "admissions_resume", "Flag-less rerun should keep the persisted document type");
  assertHashes(flipStudentRoot, trackedFiles, afterFlip, "Flag-less rerun after a persisted override is not byte-identical");
}

// A plan document type that disagrees with the instruction-derived default
// proceeds (with a recorded rationale) and the change log carries the override
// record with the faithful official text, which stays untouched on disk.
function validateInstructionOverrideRecord() {
  const overrideRoot = path.join(validationRoot, "instruction-override");
  const evaluation = setupSourceWorkspace(overrideRoot);
  const evalPath = path.join(overrideRoot, "students", studentId, "evaluations", `${evaluation.id}.yml`);
  const officialText = "Submit a current resume with your application.";
  const rationale = "Research-focused applicant; the user asked for a full academic CV despite the resume instruction.";
  writeYaml(evalPath, {
    ...evaluation,
    document_instructions: { text: officialText },
    cv_adaptation_plan: {
      ...evaluation.cv_adaptation_plan,
      document_type: "academic_cv",
      document_type_rationale: rationale,
    },
  });

  const result = runLiveCv({ program: evaluation.id, workspace: overrideRoot, student: studentId, write: true });
  assert(result.documentType === "academic_cv", "Instruction override should proceed with the plan's academic CV");
  const changeLog = fs.readFileSync(
    path.join(overrideRoot, "students", studentId, "output", evaluation.id, "change-log.md"),
    "utf8"
  );
  assert(changeLog.includes("Document type override:"), "Change log missing the document type override record");
  assert(changeLog.includes(officialText), "Change log override record must quote the official text");
  assert(changeLog.includes(rationale), "Change log override record must carry the recorded rationale");
  const evalText = fs.readFileSync(evalPath, "utf8");
  assert(evalText.includes(officialText), "document_instructions must remain a faithful transcription after the override");
  assert(!/document_instructions:[\s\S]{0,200}?document_type:/.test(evalText), "document_instructions must not gain a structured document_type");
}

function resetValidationRoot() {
  assert(
    validationRoot.startsWith(path.join(repoRoot, "validation-output")),
    `Refusing to reset outside validation-output: ${validationRoot}`
  );
  fs.rmSync(validationRoot, { recursive: true, force: true });
  fs.mkdirSync(validationRoot, { recursive: true });
}

function setupSourceWorkspace(root) {
  const evaluation = readYaml(path.join(repoRoot, "examples", "fictional-programs", "northbridge-evaluation.yml"));
  const targetStudentRoot = path.join(root, "students", studentId);
  copyFile("examples/fictional-student/profile.yml", path.join(targetStudentRoot, "profile.yml"));
  copyFile("examples/fictional-student/evidence.yml", path.join(targetStudentRoot, "evidence.yml"));
  copyFile("examples/fictional-student/master-cv.md", path.join(targetStudentRoot, "master-cv.md"));
  writeYaml(path.join(targetStudentRoot, "evaluations", `${evaluation.id}.yml`), evaluation);
  const reportName = reportFileName(evaluation);
  writeText(path.join(targetStudentRoot, "reports", reportName), renderReport(evaluation));
  writeText(path.join(targetStudentRoot, "tracker.md"), renderTracker("# Programs Tracker\n\n", [
    trackerRowFromEvaluation(evaluation, reportName),
  ]));
  return evaluation;
}

function validateLiveResult(result, label) {
  assert(result.reviewStatus === REVIEW_STATUS, `${label} result missing review status`);
  assert(result.documentType === "academic_cv", `${label} chose unexpected document type: ${result.documentType}`);
  const artifactPath = path.join(result.outputRoot, result.artifacts.artifact);
  const planPath = path.join(result.outputRoot, result.artifacts.adaptation_plan);
  const changeLogPath = path.join(result.outputRoot, result.artifacts.change_log);
  const evidenceMapPath = path.join(result.outputRoot, result.artifacts.evidence_map);
  for (const file of [artifactPath, planPath, changeLogPath, evidenceMapPath, result.reportPath, result.trackerPath]) {
    assert(fs.existsSync(file), `${label} expected output file: ${file}`);
  }

  const html = fs.readFileSync(artifactPath, "utf8");
  const plan = fs.readFileSync(planPath, "utf8");
  const changeLog = fs.readFileSync(changeLogPath, "utf8");
  const evidenceMap = readYaml(evidenceMapPath);
  assert(plan.includes(`**Review status:** ${REVIEW_STATUS}`), `${label} plan missing review status`);
  assert(changeLog.includes("Did not edit `students/live-cv-fixture/master-cv.md`"), `${label} change log missing preservation note`);
  assert(evidenceMap.review_status === REVIEW_STATUS, `${label} evidence map missing review status`);
  assert(evidenceMap.estimated_pages === estimateHtmlPages(html), `${label} page estimate is not deterministic`);
  assert(evidenceMap.generated_claims.length > 0, `${label} evidence map missing generated claims`);
  assert(fs.readFileSync(result.reportPath, "utf8").includes("Draft output links:"), `${label} report missing draft links`);
}

function validateReportAndTracker(root, result, evaluation) {
  const report = fs.readFileSync(result.reportPath, "utf8");
  const tracker = fs.readFileSync(result.trackerPath, "utf8");
  assert(report.includes(`**Tailored CV:** ${result.links.artifact} (${REVIEW_STATUS})`), "Report header missing CV link");
  for (const link of Object.values(result.links)) {
    assert(report.includes(link), `Report missing link: ${link}`);
    assert(resolveMarkdownLink(result.reportPath, link, root), `Report link does not resolve: ${link}`);
  }
  const parsed = parseTracker(tracker);
  const row = parsed.rows.find((item) =>
    item.Institution === evaluation.institution &&
    item.Program === evaluation.program &&
    item.Degree === evaluation.degree_type &&
    item.Intake === evaluation.intake
  );
  assert(row, "Tracker row missing after approved write");
  assert(row.CV.includes(REVIEW_STATUS), "Tracker CV column missing Review Required");
  assert(resolveMarkdownLink(result.trackerPath, row.CV, root), "Tracker CV link does not resolve");
}

function validateMissingStudentFailure() {
  const missingRoot = path.join(validationRoot, "missing-student");
  const evaluation = readYaml(path.join(repoRoot, "examples", "fictional-programs", "northbridge-evaluation.yml"));
  writeYaml(path.join(missingRoot, "students", "missing", "evaluations", `${evaluation.id}.yml`), evaluation);
  let failed = false;
  try {
    runLiveCv({
      program: evaluation.id,
      workspace: missingRoot,
      student: "missing",
      dryRunRoot: path.join(validationRoot, "missing-dry-run"),
    });
  } catch (error) {
    failed = /Missing required file/.test(error.message);
  }
  assert(failed, "Missing student files should fail clearly");
}

